/** A text cell of the fixture as the workbook reader returns it: numbers are numbers, everything else stays text. */
function cell(v: string): Cell {
  return /^-?\d+(\.\d+)?$/.test(v) ? Number(v) : v;
}

/** A workbook with the same layout as the real one (tab names, title rows, header row), holding the given rows. */
export function pldSheets(rows: string[]): Sheet[] {
  const byTab = new Map<string, Cell[][]>();
  for (const r of rows) {
    const [tab, ...cells] = r.split("|");
    if (!byTab.has(tab)) byTab.set(tab, []);
    byTab.get(tab)!.push(cells.map(cell));
  }
  const title = (n: string): Cell[][] => [[`Price level distributions - ${n} intervals [notes 1-21]`], ["This worksheet contains one table. Some cells refer to notes which can be found on the notes worksheet."], PLD_HEADER];
  const sizes: Record<string, string> = { "3b": "5p", "3c": "10p", "3d": "20p", "3e": "40p", "3f": "80p" };
  return [
    { name: "Cover Sheet", rows: [] },
    { name: "Notes", rows: [["Notes"], ["This worksheet contains one table. "], ["Note number ", "Note text "], [17, "Values shown as \"[x]\" represent data that are not available. All summary statistics and histogram bin values are shown as \"[x]\" where a row contains fewer than 10 observations and the sample size is considered too small for reliable results, or where publication could disclose confidential information about the underlying data."]] },
    { name: "3a", rows: [["Price level distributions - ID lookup [note 9]"], ["This worksheet contains one table. Some cells refer to notes which can be found on the notes worksheet."], ["ID_DESC", "CS_ID", "CS_DESC", "COICOP5_ID", "COICOP5_DESC", "TABLE_ID"], ["RICE - BASMATI OR JASMINE", "CP0111101", "RICE, IN ALL FORMS (EXCL. RICE FLOUR)", "CP01111", "RICE", "3b"], ["EGGS - FREE-RANGE", "CP0114801", "EGGS, FROM CHICKENS", "CP01147", "EGGS", "3c"]] },
    ...["3b", "3c", "3d", "3e", "3f"].map((n) => ({ name: n, rows: [...title(sizes[n]), ...(byTab.get(n) ?? [])] })),
  ];
}
